#!/usr/bin/env python3
"""Builds the sparse bitmap fonts of src/ui/fonts/ (stage 7b, own tool).

Each line of tools/fonts/fonts.txt describes one font; this script renders its glyphs with FreeType
and writes <name>.h: a 1-bit bitmap (rows padded to bytes, MSB first), Adafruit GFX glyph records and
the sorted code points (src/ui/fonts/SparseFontBase.h, drawn by src/ui/GlyphText.h).

  python3 tools/fonts/make_font.py --all FONT_DIR          every font of fonts.txt into src/ui/fonts/
  python3 tools/fonts/make_font.py --only NAME FONT_DIR    one of them

FONT_DIR holds the source files named in fonts.txt (Montserrat[wght].ttf from google/fonts,
materialdesignicons-webfont.ttf from @mdi/font 7.4.47). Needs: pip install freetype-py.

Metrics: a glyph's y offset is (1 - bitmap top), one pixel lower than Adafruit's convention; the
layouts of the dashboard are tuned to it. Glyphs without pixels (the space) aren't stored: the
renderer advances half the font size for them.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SPEC = os.path.join(HERE, "fonts.txt")
OUT = os.path.join(REPO, "src", "ui", "fonts")


def parse_glyphs(text):
    """'0123:' -> code points of the characters; 'U+F0026 U+F0079' or '0xF0026,...' -> those codes."""
    codes = set()
    for part in text.replace(",", " ").split():
        low = part.lower()
        if low.startswith("u+") or low.startswith("0x"):
            codes.add(int(part[2:], 16))
        else:
            codes.update(ord(c) for c in part)
    return sorted(codes)


def read_spec(path=SPEC):
    """name | source file | size | weight (0 = the file's default) | threshold [hinted] | glyphs

    "hinted": FreeType's light auto-hinting snaps the strokes to whole pixels before the threshold
    (clean 1-bit text without stray edge pixels); without it the outline is rendered unhinted."""
    fonts = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            name, source, size, weight, threshold, glyphs = [p.strip() for p in line.split("|", 5)]
            thr = threshold.split()
            if len(thr) not in (1, 2) or (len(thr) == 2 and thr[1] != "hinted"):
                raise SystemExit("%s: threshold must be a number, optionally followed by 'hinted'" % name)
            fonts.append({"name": name, "source": source, "size": int(size), "weight": float(weight),
                          "threshold": int(thr[0]), "hinted": len(thr) == 2,
                          "codes": parse_glyphs(glyphs.replace("\\s", " "))})
    return fonts


def pack_rows(buffer, width, height, pitch, threshold):
    """FreeType's 8-bit coverage to rows of bits (MSB first, each row padded to whole bytes)."""
    out = bytearray()
    for y in range(height):
        row = buffer[y * pitch:y * pitch + width]
        for start in range(0, width, 8):
            byte = 0
            for i, value in enumerate(row[start:start + 8]):
                if value > threshold:
                    byte |= 0x80 >> i
            out.append(byte)
    return out


def render(font, font_dir):
    import freetype  # only needed for rendering (the tests of the format don't need it)
    face = freetype.Face(os.path.join(font_dir, font["source"]))
    if font["weight"]:
        face.set_var_design_coords((font["weight"],))
    face.set_pixel_sizes(0, font["size"])
    bitmap, glyphs, codes = bytearray(), [], []
    for code in font["codes"]:
        if face.get_char_index(code) == 0:
            raise SystemExit("%s: U+%04X is not in %s" % (font["name"], code, font["source"]))
        hinting = (freetype.FT_LOAD_TARGET_LIGHT | freetype.FT_LOAD_FORCE_AUTOHINT) if font.get("hinted") \
            else freetype.FT_LOAD_TARGET_NORMAL
        face.load_char(chr(code), freetype.FT_LOAD_RENDER | hinting)
        g = face.glyph
        bm = g.bitmap
        if bm.width == 0 or bm.rows == 0:
            continue  # the space: not stored
        if len(bitmap) > 0xFFFF:  # GFXglyph.bitmapOffset is 16 bits
            raise SystemExit("%s: more than 64 KB of bitmap: split the font or make it smaller" % font["name"])
        glyphs.append((len(bitmap), bm.width, bm.rows, g.advance.x >> 6, g.bitmap_left, 1 - g.bitmap_top))
        codes.append(code)
        bitmap += pack_rows(bytes(bm.buffer), bm.width, bm.rows, bm.pitch, font["threshold"])
    return bitmap, glyphs, codes


def header(font, bitmap, glyphs, codes):
    n = font["name"]
    lines = ["#pragma once",
             "// Generated by tools/fonts/make_font.py from %s, %d px%s, threshold %d%s (tools/fonts/fonts.txt)."
             % (font["source"], font["size"], ", weight %g" % font["weight"] if font["weight"] else "", font["threshold"],
                ", hinted" if font.get("hinted") else ""),
             "// %d glyphs, %d bitmap bytes. Don't edit: change fonts.txt and build again." % (len(codes), len(bitmap)),
             "#include \"SparseFontBase.h\"", "",
             "const uint8_t %s_Bitmaps[] PROGMEM = {" % n]
    for i in range(0, len(bitmap), 16):
        lines.append("  " + ",".join("0x%02X" % b for b in bitmap[i:i + 16]) + ",")
    lines += ["};", "", "const uint32_t %s_CharMap[] PROGMEM = {" % n]
    for i in range(0, len(codes), 12):
        lines.append("  " + ",".join("0x%X" % c for c in codes[i:i + 12]) + ",")
    lines += ["};", "", "const GFXglyph %s_Glyphs[] PROGMEM = {" % n]
    lines += ["  {%d, %d, %d, %d, %d, %d}," % g for g in glyphs]
    lines += ["};", "", "const SparseGFXfont %s PROGMEM = {%s_Bitmaps, %s_Glyphs, %s_CharMap, %d, %d};"
              % (n, n, n, n, len(codes), font["size"]), ""]
    return "\n".join(lines)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("font_dir")
    group = ap.add_mutually_exclusive_group(required=True)
    group.add_argument("--all", action="store_true")
    group.add_argument("--only")
    ap.add_argument("--out", default=OUT)
    args = ap.parse_args(argv)
    fonts = [f for f in read_spec() if args.all or f["name"] == args.only]
    if not fonts:
        raise SystemExit("no such font in fonts.txt")
    for font in fonts:
        bitmap, glyphs, codes = render(font, args.font_dir)
        with open(os.path.join(args.out, font["name"] + ".h"), "w", encoding="utf-8", newline="\n") as f:
            f.write(header(font, bitmap, glyphs, codes))
        print("%-16s %4d glyphs %6d bytes" % (font["name"], len(codes), len(bitmap)))


if __name__ == "__main__":
    main(sys.argv[1:])
