"""Tests of tools/fonts/make_font.py (no FreeType needed). Run: python3 -m unittest discover -s tools/fonts"""
import os
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_font as mf  # noqa: E402


class MakeFontTest(unittest.TestCase):
    def test_glyph_lists(self):
        self.assertEqual(mf.parse_glyphs("ba:"), [ord(":"), ord("a"), ord("b")])
        self.assertEqual(mf.parse_glyphs("U+F0079 0xF0026"), [0xF0026, 0xF0079])

    def test_pack_rows(self):
        # 10 px wide, 2 rows: each row takes 2 bytes, MSB first; values above the threshold are ink.
        buf = bytes([200] * 10 + [0, 255, 0, 0, 0, 0, 0, 0, 0, 255])
        self.assertEqual(bytes(mf.pack_rows(buf, 10, 2, 10, 20)), bytes([0xFF, 0xC0, 0x40, 0x40]))
        # A pitch larger than the width (FreeType may pad rows): the padding is ignored.
        padded = bytes([255, 0, 0, 0, 0, 255, 9, 9])
        self.assertEqual(bytes(mf.pack_rows(padded, 2, 2, 4, 20)), bytes([0x80, 0x40]))

    def test_spec_is_complete(self):
        fonts = mf.read_spec()
        names = [f["name"] for f in fonts]
        for n in ("epaperFont", "Heading_22", "MDI_22_Sparse", "MDI_80_Sparse", "ClockDigits_110"):
            self.assertIn(n, names)
        for f in fonts:  # each font in the firmware's folder, generated by this tool
            path = os.path.join(mf.OUT, f["name"] + ".h")
            with open(path, encoding="utf-8") as h:
                self.assertIn("Generated by tools/fonts/make_font.py", h.read(400))

    def test_header_format(self):
        font = {"name": "T", "source": "x.ttf", "size": 16, "weight": 0, "threshold": 20}
        text = mf.header(font, bytearray([1, 2]), [(0, 8, 2, 9, 0, -10)], [0x41])
        self.assertIn("const SparseGFXfont T PROGMEM = {T_Bitmaps, T_Glyphs, T_CharMap, 1, 16};", text)
        self.assertIn("{0, 8, 2, 9, 0, -10},", text)


if __name__ == "__main__":
    unittest.main()
