#!/usr/bin/env python3
"""Builds the setup app (web/) into src/web/generated/WebApp.h (docs/plans/STAGE5_SETUP_APP.md).

Inlines app.css and the <script src> files (layout.js, i18n.js, app.js) into web/index.html, strips comments, gzips the result
and writes it as a byte array. Standard library only.

    python3 tools/web/build.py           write the header
    python3 tools/web/build.py --check   exit 1 if the header is out of date or the app too big

The check compares the sha256 of the uncompressed bundle (zlib output differs between machines).
"""
import gzip
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WEB = ROOT / "web"
OUT = ROOT / "src" / "web" / "generated" / "WebApp.h"
LIMIT = 60 * 1024


def strip_css(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    lines = (line.strip() for line in css.splitlines())
    return "\n".join(line for line in lines if line)


def strip_js(js):
    # Conservative: drops whole-line // comments, indentation and blank lines only (no tokenizer,
    # so nothing inside strings or regexes is touched).
    out = []
    for line in js.splitlines():
        s = line.strip()
        if not s or s.startswith("//"):
            continue
        out.append(s)
    return "\n".join(out)


def bundle():
    html = (WEB / "index.html").read_text(encoding="utf-8")

    def css(m):
        return "<style>\n" + strip_css((WEB / m.group(1)).read_text(encoding="utf-8")) + "\n</style>"

    def js(m):
        src = (WEB / m.group(1)).read_text(encoding="utf-8")
        if re.search(r"</script", src, re.I):
            sys.exit("build.py: %s contains '</script'; it would end the inlined script" % m.group(1))
        return "<script>\n" + strip_js(src) + "\n</script>"

    html, n_css = re.subn(r'<link rel="stylesheet" href="([^"]+)">', css, html)
    html, n_js = re.subn(r'<script src="([^"]+)"></script>', js, html)
    if n_css != 1 or n_js != 3:
        sys.exit("build.py: expected 1 stylesheet and 3 scripts in web/index.html, found %d and %d" % (n_css, n_js))
    html = "\n".join(line.strip() for line in html.splitlines() if line.strip())
    return html.encode("utf-8")


def header(raw, gz):
    digest = hashlib.sha256(raw).hexdigest()
    lines = [
        "#pragma once",
        "// Generated by tools/web/build.py from web/: do not edit. Rebuild: python3 tools/web/build.py",
        "#include <stddef.h>",
        "#include <stdint.h>",
        '#define WEB_APP_SHA256 "%s"' % digest,
        "static const size_t WEB_APP_GZ_LEN = %d;" % len(gz),
        "static const uint8_t WEB_APP_GZ[] = {",
    ]
    for i in range(0, len(gz), 16):
        lines.append("  " + ",".join("0x%02x" % b for b in gz[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    raw = bundle()
    gz = gzip.compress(raw, 9, mtime=0)
    digest = hashlib.sha256(raw).hexdigest()
    print("web app: %d bytes, %d bytes gzipped (limit %d)" % (len(raw), len(gz), LIMIT))
    if len(gz) > LIMIT:
        print("build.py: the gzipped app is larger than %d bytes: make it smaller" % LIMIT)
        return 1
    if check:
        if not OUT.exists():
            print("build.py: %s is missing: run python3 tools/web/build.py" % OUT.relative_to(ROOT))
            return 1
        m = re.search(r'#define WEB_APP_SHA256 "([0-9a-f]{64})"', OUT.read_text(encoding="utf-8"))
        if not m or m.group(1) != digest:
            print("build.py: %s is out of date with web/: run python3 tools/web/build.py and commit it" % OUT.relative_to(ROOT))
            return 1
        print("%s is up to date" % OUT.relative_to(ROOT))
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(header(raw, gz), encoding="utf-8")
    print("wrote %s" % OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
