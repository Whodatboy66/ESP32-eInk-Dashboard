#pragma once
// Calendar days without time zones (stage 7b): one place for the day-number arithmetic the
// holidays, the calendar parser, the services and the personal widgets share. Proleptic Gregorian,
// day 0 = 1970-01-01 (H. Hinnant's days_from_civil / civil_from_days).

namespace civil {

inline long daysFromCivil(int y, int m, int d) {
  y -= m <= 2;
  const long era = (y >= 0 ? y : y - 399) / 400;
  const long yoe = y - era * 400;
  const long doy = (153 * (m + (m > 2 ? -3 : 9)) + 2) / 5 + d - 1;
  return era * 146097 + yoe * 365 + yoe / 4 - yoe / 100 + doy - 719468;
}

inline void civilFromDays(long z, int& y, int& m, int& d) {
  z += 719468;
  const long era = (z >= 0 ? z : z - 146096) / 146097;
  const long doe = z - era * 146097;
  const long yoe = (doe - doe / 1460 + doe / 36524 - doe / 146096) / 365;
  const long doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
  const long mp = (5 * doy + 2) / 153;
  d = static_cast<int>(doy - (153 * mp + 2) / 5 + 1);
  m = static_cast<int>(mp < 10 ? mp + 3 : mp - 9);
  y = static_cast<int>(yoe + era * 400 + (m <= 2));
}

// 0 = Monday ... 6 = Sunday.
inline int weekdayMonday0(long day) { return static_cast<int>(((day % 7) + 7 + 3) % 7); }

}  // namespace civil
